// Worker build helper.
//  - proxy/version.mjs: WORKER_VERSION, a fingerprint (sha256, 12 hex) of the Worker's source (proxy/worker-src.mjs and
//    every module it imports, version file excluded). The deployed Worker reports it at /version; the app and the
//    "Check Worker" workflow compare it with the repo's to catch a stale deployment.
//  - proxy/worker.js: a paste-ready single-file bundle, only for a hand-made Worker (the connected Worker is built by
//    Cloudflare from wrangler.toml).
// `node tools/build-worker.mjs` writes both; `--check` fails if either is out of date (run by the tests).
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const root = new URL("..", import.meta.url);
const read = (p) => readFileSync(new URL(p, root), "utf8");
const VERSION_FILE = "proxy/version.mjs";

export function bundle({ includeVersion = true } = {}) {
  const seen = new Set(), parts = [];
  function add(path) {
    if (seen.has(path)) return; seen.add(path);
    if (path === VERSION_FILE && !includeVersion) return;
    const src = read(path);
    for (const m of src.matchAll(/^import \{[^}]*\} from "(\.\.?\/[\w./-]+\.mjs)";$/gm)) {
      add(new URL(m[1], new URL(path, root)).pathname.slice(new URL(root).pathname.length));
    }
    const body = src.replace(/^import .*;$/gm, "").replace(/^export default /m, "const __worker = ").replace(/^export /gm, "");
    parts.push(`// ---- ${path}\n${body.trim()}\n`);
  }
  add("proxy/worker-src.mjs");
  // All modules share one scope in the bundle: duplicate top-level names would silently shadow each other.
  const names = new Map();
  for (const part of parts) for (const m of part.matchAll(/^(?:const|let|var|function|class|async function)\s+([A-Za-z_$][\w$]*)/gm)) {
    if (names.has(m[1])) throw new Error(`duplicate top-level name ${m[1]} in bundle (also in ${names.get(m[1])})`);
    names.set(m[1], part.split("\n")[0]);
  }
  return `// GENERATED by tools/build-worker.mjs from proxy/worker-src.mjs — paste this whole file into a Cloudflare Worker.\n// Do not edit by hand; edit the sources and rebuild.\n\n${parts.join("\n")}\nexport default __worker;\n`;
}

/** Fingerprint of the Worker's source, independent of the version file itself. */
export function sourceVersion() { return createHash("sha256").update(bundle({ includeVersion: false })).digest("hex").slice(0, 12); }
export function versionFile(v = sourceVersion()) {
  return `// GENERATED by tools/build-worker.mjs: fingerprint of the Worker's source. The deployed Worker reports it at /version.\nexport const WORKER_VERSION = "${v}";\n`;
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split("/").pop())) {
  if (process.argv.includes("--check")) {
    const problems = [];
    let current = ""; try { current = read(VERSION_FILE); } catch { /* missing */ }
    if (current !== versionFile()) problems.push(`${VERSION_FILE} is out of date`);
    if (read("proxy/worker.js") !== bundle()) problems.push("proxy/worker.js is out of date");
    if (problems.length) { console.error(`${problems.join("; ")}: run node tools/build-worker.mjs`); process.exit(1); }
  } else {
    writeFileSync(new URL(VERSION_FILE, root), versionFile());
    writeFileSync(new URL("proxy/worker.js", root), bundle());
    console.log(`wrote ${VERSION_FILE} (${sourceVersion()}) and proxy/worker.js`);
  }
}
